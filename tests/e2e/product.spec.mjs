async function replayModels(context) {
  const modelRoot = path.resolve(process.env.CATCH_MODEL_DIR || '.catch-cache/models', 'Xenova/all-MiniLM-L6-v2')
  const ocrRoot = path.resolve('.catch-cache/ocr')
  for (const asset of [...embeddingAssets, ...ocrAssets]) {
    const source = path.join(asset.name === 'eng.traineddata' ? ocrRoot : modelRoot, asset.name)
    await context.route(url => url.href === asset.url, route => route.fulfill({
      path: source, headers: { 'content-type': 'application/octet-stream', 'access-control-allow-origin': '*' },
    }))
  }
}

