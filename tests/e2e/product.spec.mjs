function showcaseState(page) {
  return page.evaluate(() => new Promise((resolve, reject) => {
    const opening = indexedDB.open('catch-library', 2)
    opening.onerror = () => reject(opening.error)
    opening.onsuccess = () => {
      const database = opening.result
      const request = database.transaction('clips').objectStore('clips').getAll()
      request.onerror = () => { database.close(); reject(request.error) }
      request.onsuccess = () => {
        const clips = request.result
        const demo = clips.filter(clip => clip.demo && clip.id.startsWith('showcase-v1-'))
        resolve({
          uid: clips.find(clip => clip.title === 'Personal regression note')?.id,
          active: demo.filter(clip => !clip.trashed).length,
          total: demo.length,
          attachments: demo.flatMap(clip => clip.attachments ?? []).filter(file => file.blob.size > 100),
          pdfsRead: demo.filter(clip => clip.processing?.passages.some(passage => passage.method === 'pdf')).length,
          classified: demo.some(clip => !!clip.prediction?.category),
        })
        database.close()
      }
    }
  }))
}

